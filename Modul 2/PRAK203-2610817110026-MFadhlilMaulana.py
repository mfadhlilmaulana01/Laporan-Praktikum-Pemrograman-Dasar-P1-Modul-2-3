a = float(input("Masukkan angka pertama: "))
b = float(input("Masukkan angka kedua: "))
i = float(input("Masukkan angka ketiga: "))
j = float(input("Masukkan angka keempat: "))
x = float(input("Masukkan angka kelima: "))
y = float(input("Masukkan angka keenam: "))
result = (a - b) * (i / j) - (x + y)

print(f"{result:.3f}")